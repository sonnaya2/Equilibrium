function get(path) {
  return new Promise((resolve, reject) => {
    https
      .get(
        {
          hostname: "runescape.wiki",
          path,
          headers: {
            "User-Agent": "Rs3Equilibrium/1.0 (archaeology research; local)",
            Accept: "application/json",
          },
        },
        (res) => {
          let data = "";
          res.on("data", (c) => (data += c));
          res.on("end", () => resolve(data));
        },
      )
      .on("error", reject);
  });
}

async function wikitext(page) {
  const raw = await get(
    `/api.php?action=parse&page=${encodeURIComponent(page)}&prop=wikitext&format=json`,
  );
  const j = JSON.parse(raw);
  return j.parse?.wikitext?.["*"] || "";
}

